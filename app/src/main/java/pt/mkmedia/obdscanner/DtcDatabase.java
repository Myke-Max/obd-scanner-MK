    public static String describe(String code) {
        String exact = M.get(code);
        if (exact != null) return exact;
        char sys = code.charAt(0);
        char kind = code.charAt(1);
        boolean generic = (kind == '0') || (sys == 'P' && kind == '2');
        String where;
        switch (sys) {
            case 'P':
                where = "двигатель или коробка передач";
                if (generic && code.length() >= 3) {
                    char g = code.charAt(2);
                    if (g == '0' || g == '1' || g == '2') where = "система топлива и воздуха";
                    else if (g == '3') where = "система зажигания, пропуски зажигания";
                    else if (g == '4') where = "системы контроля выбросов";
                    else if (g == '5') where = "скорость, холостой ход, вспомогательные системы";
                    else if (g == '6') where = "бортовой компьютер и его цепи";
                    else if (g == '7' || g == '8') where = "коробка передач";
                }
                break;
            case 'C':
                where = "шасси (тормоза/АБС, подвеска, рулевое)";
                break;
            case 'B':
                where = "кузов (подушки безопасности, комфорт, салон)";
                break;
            default:
                where = "связь между блоками управления";
        }
        return (generic ? "Стандартная ошибка: " : "Ошибка, специфичная для марки (точное описание зависит от производителя): ") + where;
    }
